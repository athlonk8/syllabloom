export function translate(locale: Locale, key: string, values: TranslationValues = {}): string {
  let text = messages[locale][key] ?? messages.en[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    if (value !== undefined && value !== null) text = text.replaceAll("{" + name + "}", String(value));
  }
  return text;
}

export function detectLocale(): Locale {
  const requested = new URLSearchParams(window.location.search).get("lang");
  if (requested === "en" || requested === "zh") return requested;
  try {
    return window.localStorage.getItem("syllabloom.locale") === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}

export function localeLink(locale: Locale): string {
  const url = new URL(window.location.href);
  url.searchParams.set("lang", locale);
  return url.pathname + url.search + url.hash;
}
